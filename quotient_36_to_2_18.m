procedure C36YEffective(weights,classes,remaining,start,current,~out)
 if remaining eq 0 then Include(~out,current);return;end if;
 for i in [start..#weights] do
  if weights[i] le remaining then
   C36YEffective(weights,classes,remaining-weights[i],i,current+classes[i],~out);
  end if;
 end for;
end procedure;
